const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader']});let checks=0;const errors=[];
 const check=(ok,msg)=>{assert.ok(ok,msg);checks++;console.log('PASS '+msg);};
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/index.html');
  await page.evaluate(()=>localStorage.setItem('travel-globe-areas-v2',JSON.stringify({sentinel:'preserve saved visits'})));
  check((await page.goto('http://127.0.0.1:4173/structure.html')).status()===200,'structure page loads');
  await page.waitForFunction(()=>window.globeStructure?.ready,{},{timeout:60000});
  let data=await page.evaluate(()=>globeStructure.snapshot());
  check(data.view==='cutaway'&&data.visibleSections===8,'cutaway opens with four shell sections removed');
  check(data.tiles>=300&&data.tiles<320&&data.visibleTiles>150&&data.visibleTiles<320,'cutaway reveals frame by removing front carrier tiles');
  check(data.dimensions.shellRadius===152.5&&data.dimensions.terrain===25,'model uses 305 mm globe and 25× terrain');
  check(data.prototype.cells===117&&data.prototype.pitch===3,'prototype has 13 × 9 cells at 3 mm pitch');
  check(data.prototypeInnerCenter>1&&data.prototypeInnerCenter<3,'prototype curved underside alignment is physically plausible');
  check(await page.evaluate(()=>JSON.parse(localStorage.getItem('travel-globe-areas-v2')).sentinel==='preserve saved visits'),'structure viewer preserves existing travel storage');
  await page.screenshot({path:'artifacts/structure-cutaway.png'});
  await page.locator('[data-view=assembled]').click();
  check((await page.evaluate(()=>globeStructure.snapshot())).visibleSections===12,'assembled view closes all exterior sections');
  await page.screenshot({path:'artifacts/structure-assembled.png'});
  await page.locator('[data-view=exploded]').click();
  await page.locator('#spread').fill('85');
  check((await page.evaluate(()=>globeStructure.snapshot())).spread===.85,'exploded spacing is adjustable');
  await page.screenshot({path:'artifacts/structure-exploded.png'});
  await page.locator('[data-view=frame]').click();
  data=await page.evaluate(()=>globeStructure.snapshot());check(data.visibleTiles===0&&data.visibleSections===0,'frame view hides exterior and LED tiles');
  await page.screenshot({path:'artifacts/structure-frame.png'});
  await page.locator('[data-view=prototype]').click();
  await page.locator('#spread').fill('60');
  data=await page.evaluate(()=>globeStructure.snapshot());check(data.sampleShellOffset===18&&data.sampleBaffleOffset===7.8,'prototype separates shell and baffles in correct order');
  await page.screenshot({path:'artifacts/structure-prototype.png'});
  await page.locator('[data-layer=baffles]').uncheck();
  check(!(await page.evaluate(()=>globeStructure.snapshot())).visibility.baffles,'layer controls hide selected component');
  check((await page.locator('#part-title').textContent())==='Shaped optical cells','layer selection shows matching component notes');
  await page.locator('[data-layer=baffles]').check();await page.locator('#spread').fill('0');
  check((await page.evaluate(()=>globeStructure.snapshot())).sampleShellOffset===0,'prototype can be viewed with assembled spacing');
  await page.locator('#spread').fill('60');
  const downloadPromise=page.waitForEvent('download');await page.locator('#save-image').click();const download=await downloadPromise;
  check(download.suggestedFilename()==='globe-prototype-concept.png','review image download is clearly named');
  await download.saveAs('artifacts/structure-prototype-render.png');
  const png=await fs.readFile('artifacts/structure-prototype-render.png');check(png.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))&&png.length>10000,'download contains a rendered PNG');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:4173/structure.html');await mobile.waitForFunction(()=>window.globeStructure?.ready,{},{timeout:60000});
  check(await mobile.evaluate(()=>document.body.scrollWidth===innerWidth),'structural page fits phone viewport');
  await mobile.screenshot({path:'artifacts/structure-mobile.png'});
  await mobile.locator('[data-view=prototype]').click();
  check(await mobile.locator('#view-title').textContent()==='The first thing to fabricate','prototype view accessible on phone');
  await mobile.screenshot({path:'artifacts/structure-prototype-mobile.png'});
  check(errors.length===0,'no structural viewer runtime errors');
  console.log('Completed '+checks+' structural checks.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
